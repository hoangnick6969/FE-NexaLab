import { api, mutate } from "../../lib/api";

/**
 * Teacher AI lab-challenge drafting (TAI-06) client contract, mirroring BE `spec-teacher-ai-lab-drafting`
 * `implementation-contract.md`. Owner-only Class Space routes; the backend enforces ownership, so hiding UI is never the
 * authorization. This module is loaded by the teacher lesson editor only (dynamic import), never by the entry, student
 * or parent bundles (`npm run test:lab-challenge-bundle`). The AI only proposes an allowlisted lab and parameter values;
 * the server engine verifies them, and the student objective is always generated by the server from those values.
 */
export type LabParamValue = number | string;
export type LabProposalPayload = {
  labId: string;
  challengeParams: Record<string, LabParamValue>;
  /** Teacher-only. Never shown to students and never stored on the lesson. */
  rationale: string;
  outcomeCodes: string[];
  sourceRefs: string[];
};
export type EngineVerdict = "passed" | "partial" | "needs_practice";
export type EngineResult = { label: string; verdict: EngineVerdict | string };
export type LabProposalCard = {
  id: string;
  position: number;
  proposal: LabProposalPayload;
  /** Deterministic objective sentence the student will see after the normal publish and assignment. */
  objectivePreview: string | null;
  engineResults: EngineResult[];
  engineVersion: string | null;
  modelRef: string | null;
  referenceSource: "PACK" | "CONFIG" | "BUILTIN" | null;
  decision: null | { decision: "ACCEPTED" | "REJECTED"; reasonCode: string | null; at: string };
};
export type LabJobStatus = "PENDING" | "RUNNING" | "SUCCEEDED" | "FAILED" | "CANCELLED";
export type DroppedProposal = { position: number; reasonCodes: string[] };
export type LabJobView = {
  id: string;
  classId: string;
  lessonId: string;
  purpose: "DRAFT_LAB_CHALLENGE";
  status: LabJobStatus;
  failureCode: string | null;
  requestedCount: number;
  validCount: number | null;
  droppedCount: number | null;
  dropped: DroppedProposal[];
  lessonChangedSinceGeneration: boolean;
  appliedLessonId: string | null;
  appliedItemId: string | null;
  /** Present while AI credits are on. */
  credits?: { estimated: number; state: "reserved" | "settled" | "refunded"; charged: number | null; refunded: number | null } | null;
  createdAt: string;
  completedAt: string | null;
  proposals?: LabProposalCard[];
};
export type ApplyResult = {
  jobId: string;
  itemId: string;
  lesson: { id: string; labId: string | null; challengeParams: Record<string, LabParamValue> | null; status: string };
  objectivePreview: string;
};
export type LabQuota = { purpose: string; dailyLimit: number; usedLast24h: number; activeJobs: number; concurrencyLimit: number; resetsAt: string | null };
export type CreateLabJobInput = { lessonId: string; proposalCount: number; instruction?: string; confirmedCredits?: number };

export const MAX_PROPOSALS = 3;
export const ACTIVE_STATUSES: LabJobStatus[] = ["PENDING", "RUNNING"];
/** Same polling contract as the other Teacher AI jobs: every 2 s while active, then a recoverable "still processing" state. */
export const POLL_INTERVAL_MS = 2_000;
export const POLL_LIMIT_MS = 120_000;

export const labQuota = () => api<LabQuota>("/me/ai-quota?purpose=DRAFT_LAB_CHALLENGE");
export const listLabJobs = (classId: string) => api<{ items: LabJobView[]; nextCursor: string | null }>(`/classes/${classId}/ai-jobs?purpose=DRAFT_LAB_CHALLENGE&limit=10`);
export const getLabJob = (classId: string, jobId: string) => api<LabJobView>(`/classes/${classId}/ai-jobs/${jobId}`);
export const createLabJob = (classId: string, input: CreateLabJobInput, key: string) =>
  mutate<LabJobView>(`/classes/${classId}/ai-jobs`, "POST", { purpose: "DRAFT_LAB_CHALLENGE", ...input }, key);
export const cancelLabJob = (classId: string, jobId: string) => api<LabJobView>(`/classes/${classId}/ai-jobs/${jobId}/cancel`, "POST", {});
export const rejectLabProposal = (classId: string, jobId: string, itemId: string, reasonCode: string) =>
  api<LabJobView>(`/classes/${classId}/ai-jobs/${jobId}/items/${itemId}/decisions`, "POST", { decision: "REJECTED", reasonCode });
export const applyLabProposal = (classId: string, jobId: string, itemId: string, key: string) =>
  mutate<ApplyResult>(`/classes/${classId}/ai-jobs/${jobId}/items/${itemId}/apply`, "POST", {}, key);
